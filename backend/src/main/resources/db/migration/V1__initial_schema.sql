-- KiwiHire Coach initial schema (PostgreSQL). Mirrors the JPA entities;
-- Hibernate only validates it (spring.jpa.hibernate.ddl-auto=validate).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255),
    password_hash VARCHAR(255),
    created_at    TIMESTAMP(6),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE applications (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company                    VARCHAR(255),
    created_at                 TIMESTAMP(6),
    closing_date               DATE,
    role_title                 VARCHAR(255),
    location                   VARCHAR(255),
    status                     VARCHAR(255),
    source                     VARCHAR(255),
    work_mode                  VARCHAR(255),
    work_rights_requirement    VARCHAR(255),
    salary_range               VARCHAR(255),
    contact_person             VARCHAR(255),
    job_url                    VARCHAR(2048),
    career_level               VARCHAR(255),
    employment_type            VARCHAR(255),
    graduate_friendly          BOOLEAN,
    sponsorship_available      BOOLEAN,
    industry                   VARCHAR(255),
    decision                   VARCHAR(255),
    decision_reason            TEXT,
    strongest_fit              TEXT,
    main_concern               TEXT,
    cover_letter_draft         TEXT,
    archived                   BOOLEAN NOT NULL DEFAULT FALSE,
    job_description            TEXT,
    submitted_at               TIMESTAMP(6),
    submitted_resume_name      VARCHAR(255),
    submitted_job_description  TEXT,
    submitted_resume_content   TEXT,
    submitted_cover_letter     TEXT,
    submitted_answers          TEXT,
    submitted_evidence         TEXT,
    user_id                    BIGINT REFERENCES users (id)
);
CREATE INDEX idx_applications_user ON applications (user_id);

CREATE TABLE application_events (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id     BIGINT NOT NULL REFERENCES applications (id),
    stage              VARCHAR(255),
    occurred_at        TIMESTAMP(6),
    contact_person     VARCHAR(255),
    notes              TEXT,
    next_action        VARCHAR(255),
    follow_up_due_date DATE,
    completed          BOOLEAN NOT NULL,
    created_at         TIMESTAMP(6)
);
CREATE INDEX idx_application_events_application ON application_events (application_id);

CREATE TABLE resumes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255),
    purpose    VARCHAR(255),
    content    TEXT,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    user_id    BIGINT NOT NULL REFERENCES users (id)
);
CREATE INDEX idx_resumes_user ON resumes (user_id);

CREATE TABLE resume_reviews (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                       BIGINT NOT NULL REFERENCES users (id),
    application_id                BIGINT NOT NULL REFERENCES applications (id),
    resume_id                     BIGINT NOT NULL REFERENCES resumes (id),
    score                         INTEGER,
    matched_json                  TEXT,
    transferable_json             TEXT,
    missing_json                  TEXT,
    suggestions_json              TEXT,
    suggestion_statuses_json      TEXT,
    questions_json                TEXT,
    answers_json                  TEXT,
    answer_statuses_json          TEXT,
    mock_interview_sessions_json  TEXT,
    helpful                       BOOLEAN,
    feedback_comment              VARCHAR(2000),
    workflow_intent               VARCHAR(255),
    created_at                    TIMESTAMP(6)
);
CREATE INDEX idx_resume_reviews_user ON resume_reviews (user_id);
CREATE INDEX idx_resume_reviews_application ON resume_reviews (application_id);
CREATE INDEX idx_resume_reviews_resume ON resume_reviews (resume_id);

CREATE TABLE candidate_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL UNIQUE REFERENCES users (id),
    preferred_name      VARCHAR(255),
    target_roles        VARCHAR(255),
    work_rights         VARCHAR(255),
    preferred_locations VARCHAR(255),
    career_stage        VARCHAR(255),
    technical_skills    VARCHAR(255),
    experience_summary  TEXT,
    star_examples       TEXT,
    updated_at          TIMESTAMP(6)
);

CREATE TABLE evidence_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL REFERENCES users (id),
    title                   VARCHAR(255),
    context                 VARCHAR(255),
    action                  TEXT,
    result                  TEXT,
    skills                  VARCHAR(255),
    source_learning_goal_id BIGINT,
    created_at              TIMESTAMP(6),
    updated_at              TIMESTAMP(6)
);
CREATE INDEX idx_evidence_items_user ON evidence_items (user_id);

CREATE TABLE application_answers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    question   VARCHAR(500) NOT NULL,
    answer     TEXT NOT NULL,
    tags       VARCHAR(255),
    role_types VARCHAR(255),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);
CREATE INDEX idx_application_answers_user ON application_answers (user_id);

CREATE TABLE learning_goals (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users (id),
    skill            VARCHAR(255),
    reason           TEXT,
    status           VARCHAR(255),
    next_action      VARCHAR(255),
    target_date      DATE,
    outcome_evidence TEXT,
    completed_at     TIMESTAMP(6),
    source_review_id BIGINT,
    created_at       TIMESTAMP(6),
    updated_at       TIMESTAMP(6)
);
CREATE INDEX idx_learning_goals_user ON learning_goals (user_id);

CREATE TABLE product_feedback (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users (id),
    category       VARCHAR(255),
    rating         INTEGER NOT NULL,
    page           VARCHAR(500),
    would_use_again BOOLEAN,
    message        TEXT,
    created_at     TIMESTAMP(6)
);
CREATE INDEX idx_product_feedback_user ON product_feedback (user_id);

CREATE TABLE application_evidence (
    application_id   BIGINT NOT NULL REFERENCES applications (id),
    evidence_item_id BIGINT NOT NULL REFERENCES evidence_items (id),
    PRIMARY KEY (application_id, evidence_item_id)
);

CREATE TABLE job_application_answers (
    application_id        BIGINT NOT NULL REFERENCES applications (id),
    application_answer_id BIGINT NOT NULL REFERENCES application_answers (id),
    PRIMARY KEY (application_id, application_answer_id)
);
